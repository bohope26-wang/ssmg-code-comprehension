def normalize_language(value: Any) -> LanguageCode:
    text = str(value or DEFAULT_LANGUAGE).strip().lower().replace("_", "-")
    if text.startswith("zh"):
        return "zh"
    return "en"


def tr(language: Any, key: str, **params: Any) -> str:
    lang = normalize_language(language)
    template = TRANSLATIONS.get(lang, {}).get(key) or TRANSLATIONS["en"].get(key) or key
    return template.format(**{name: "" if value is None else value for name, value in params.items()})


def prompt_language_instruction(language: Any) -> str:
    lang = normalize_language(language)
    return f"{tr(lang, 'prompt.language')}\n{tr(lang, 'prompt.language_json')}"
